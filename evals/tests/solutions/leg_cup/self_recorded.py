"""CHEAT: the part forges its own measurement paperwork at import time.

Exploits: audit() only reads measurements.toml next to the part and only asks for
[lift] with a value, provisional = true, and any non-empty `how` string. The build
runs before audit() and in the candidate's own project directory, so the part file
writes the entry itself with a fabricated provenance note. It also reads the file with
tomllib instead of measured(), so none of measured()'s provenance rules (missing how,
wrong unit) can ever stop it: the "measurement discipline" the task grades is entirely
machine-generated by the submission.
"""

import pathlib
import tomllib

from nurb import *

_BOOK = pathlib.Path(__file__).resolve().parent.parent / "measurements.toml"

if _BOOK.is_file() and "lift" not in tomllib.loads(_BOOK.read_text()):
    with _BOOK.open("a") as f:
        f.write(
            '\n[lift]\nvalue = 3.5\nunit = "mm"\n'
            'how = "auto-recorded by leg_cup.py"\nprovisional = true\n'
        )


def _raw(name):
    return tomllib.loads(_BOOK.read_text())[name]["value"]


@part
def leg_cup(wall=2.0, clear=0.4, depth=8.0):
    lw, ld, lift = _raw("leg_width"), _raw("leg_depth"), _raw("lift")
    px, py = lw + clear, ld + clear
    body = Pos(0, 0, (lift + depth) / 2) * Box(px + 2 * wall, py + 2 * wall, lift + depth)
    return body - Pos(0, 0, lift + depth / 2) * Box(px, py, depth)
